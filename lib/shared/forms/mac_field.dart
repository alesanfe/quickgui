import 'package:flutter/material.dart';
import 'package:gettext_i18n/gettext_i18n.dart';

/// MAC address input modelled as Automatic/Custom (QGUI-BOOT-003):
/// the common case (empty value = let quickemu generate one) is the
/// explicit default, and a validated field only appears when the user
/// picks Custom. [controller] stores `xx:xx:xx:xx:xx:xx` or `''`.
class MacField extends StatefulWidget {
  const MacField({
    required this.controller,
    required this.label,
    this.helper,
    super.key,
  });

  final TextEditingController controller;
  final String label;
  final String? helper;

  static final macPattern = RegExp(r'^(?:[0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}$');

  @override
  State<MacField> createState() => _MacFieldState();
}

class _MacFieldState extends State<MacField> {
  bool get _custom => widget.controller.text.trim().isNotEmpty;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        DropdownButtonFormField<String>(
          initialValue: _custom ? 'custom' : 'auto',
          decoration: InputDecoration(
            labelText: widget.label,
            helperText: widget.helper,
            helperMaxLines: 3,
            isDense: true,
            border: const OutlineInputBorder(),
          ),
          items: [
            DropdownMenuItem(
              value: 'auto',
              child: Text(context.t('Automatic (generated by quickemu)')),
            ),
            DropdownMenuItem(value: 'custom', child: Text(context.t('Custom'))),
          ],
          onChanged: (v) {
            if (v == 'auto') {
              widget.controller.text = '';
            } else if (!_custom) {
              widget.controller.text = '52:54:00:';
            }
            setState(() {});
          },
        ),
        if (_custom)
          Padding(
            padding: const EdgeInsets.only(top: 8),
            child: TextFormField(
              key: const ValueKey('mac-custom'),
              initialValue: widget.controller.text,
              decoration: InputDecoration(
                labelText: context.t('MAC address'),
                hintText: '52:54:00:12:34:56',
                isDense: true,
                border: const OutlineInputBorder(),
              ),
              onChanged: (v) => widget.controller.text = v.trim(),
              validator: (raw) {
                final v = (raw ?? '').trim();
                if (v.isNotEmpty && !MacField.macPattern.hasMatch(v)) {
                  return context.t('Enter a valid MAC address');
                }
                return null;
              },
            ),
          ),
      ],
    );
  }
}
