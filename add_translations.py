def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


def entries(ids, tr=None):
    out = []
    for s in ids:
        out.append(f'msgid "{esc(s)}"\nmsgstr "{esc(tr.get(s, "")) if tr else ""}"\n')
    return '\n'.join(out)


def append(path, text):
    with open(path, encoding='utf-8') as fh:
        cur = fh.read()
    existing = set(re.findall(r'msgid "(.*)"', cur))
    todo = [s for s in missing if esc(s) not in existing and s not in existing]
    if not todo:
        print(f'{path}: nothing to add')
        return
    if not cur.endswith('\n'):
        cur += '\n'
    cur += '\n' + text(todo)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(cur)
    print(f'{path}: +{len(todo)} entries')


append('assets/translations/quickgui.pot', lambda ids: entries(ids))
append('assets/translations/en.po', lambda ids: entries(ids, {s: s for s in ids}))
append('assets/translations/es.po', lambda ids: entries(ids, ES))
